export type Lang = 'nl' | 'en'

const LANG_EVENT = 'chefshift-lang-change'

function readLang(): Lang {
  if (typeof window === 'undefined') return 'nl'
  const l = localStorage.getItem('chefshift-lang')
  return l === 'en' ? 'en' : 'nl'
}

